package handlers

import (
	"fmt"
	"net/http"
)

// type Handler struct{} объявляет структуру «главного диспетчера» для ваших запросов.
// СВЯЗАН С: Файлом cmd/api/main.go (где он создается) и будущим слоем service (бизнес-логика).
// ЗАЧЕМ: В будущем сюда мы внедрим базы данных и сервисы обмена валют, чтобы все ваши
// функции-обработчики (маршруты) имели к ним безопасный доступ. Сейчас структура пустая.
type Handler struct{}

// func NewHandler() — это функция-конструктор, создающая объект Handler.
// СВЯЗАН С: Вызывается в файле cmd/api/main.go при старте приложения.
// ЗАЧЕМ: Возвращает готовый указатель на структуру Handler, инкапсулируя сборку этого слоя.
func NewHandler() *Handler {
	return &Handler{} // Создает пустую структуру в памяти и отдает ссылку на нее
}

// InitRoutes — метод структуры Handler, который создает карту путей (эндпоинтов) вашего API.
// Связывает входящие URL-адреса из браузера с функциями вашего кода.
// Возвращает настроенный маршрутизатор (ServeMux) обратно в main.go, чтобы запустить сервер.
func (h *Handler) InitRoutes() *http.ServeMux {
	// http.NewServeMux() создает изолированный экземпляр маршрутизатора (мультиплексора).
	// ЗАЧЕМ: Локальный mux безопаснее глобального, он изолирует правила путей вашего обменника.
	mux := http.NewServeMux()

	// mux.HandleFunc связывает метод+путь с конкретной функцией, которая его обработает.
	// СВЯЗАН С: Методом handleStatus (находится ниже) и алгоритмом роутинга.
	// ЗАЧЕМ: Говорит серверу: «Если прилетит запрос GET на адрес /api/status, запусти функцию handleStatus».
	mux.HandleFunc("GET /api/status", h.handleStatus)

	// возвращает полностью укомплектованный маршрутизатор наружу.
	return mux
}

// handleStatus — это конкретная функция (обработчик), которая выполняет работу при вызове /api/status.
// СВЯЗАН С: Напрямую с клиентом (браузер, curl, Postman), который сделал запрос.
// Параметры:
//
//	w http.ResponseWriter — «канал записи», через него мы пишем ответ клиенту (заголовки, статус, текст).
//	r *http.Request — объект самого запроса, отсюда мы читаем данные от клиента (куки, JSON-тело, параметры).
//
// ЗАЧЕМ: Проверяет работоспособность сервера (Health check). В будущем тут будут функции вроде handleExchange.
func (h *Handler) handleStatus(w http.ResponseWriter, r *http.Request) {
	// w.Header().Set устанавливает HTTP-заголовок ответа.
	// ЗАЧЕМ: Мы явно говорим клиенту: «Мы отправляем тебе данные в формате JSON (application/json)».
	// Благодаря этому браузер или Postman поймут, как правильно подсветить текст ответа.
	w.Header().Set("Content-type", "application/json")

	// w.WriteHeader отправляет HTTP-статус ответа.
	// ЗАЧЕМ: Статус http.StatusOK (это число 200) сообщает клиенту, что все прошло успешно.
	w.WriteHeader(http.StatusOK)

	// fmt.Fprint форматирует строку и записывает ее прямо в ответ клиенту (в параметр w).
	// ЗАЧЕМ: Отправляет финальный JSON-текст с сообщением, что API обменника валют успешно работает.
	fmt.Fprint(w, `{"status": "running", "message": "Currency Exchange API is live"}`)
}
